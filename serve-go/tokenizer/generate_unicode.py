#!/usr/bin/env python3
"""Print the Go Unicode table used by the pre-tokenizer.

Run with the repository's .venv Python and regex 2026.9.10. See README.md.
The SHA-256 covers one class-mask byte for every code point, including
surrogates. Refuse to emit a table if the installed data does not match.
"""

import hashlib
import sys

import regex

VERSION = "2026.9.10"
EXPECTED_SHA256 = "936112a46135affeed68629aba9b4ee89c4580c6e752714b7cc9f4310b09d1e8"
PATTERNS = (r"\p{L}+", r"\p{M}+", r"\p{N}+", r"\p{P}+", r"\p{S}+", r"\s+")

if regex.__version__ != VERSION:
    sys.exit(f"expected regex {VERSION}, found {regex.__version__}")

text = "".join(map(chr, range(0x110000)))
masks = bytearray(len(text))
for bit, pattern in enumerate(PATTERNS):
    for match in regex.finditer(pattern, text):
        for codepoint in range(match.start(), match.end()):
            masks[codepoint] |= 1 << bit

digest = hashlib.sha256(masks).hexdigest()
if digest != EXPECTED_SHA256:
    sys.exit(f"Unicode mask digest {digest} != {EXPECTED_SHA256}")

# A uint32 stores the start of a run in its upper bits and its mask in the
# low six bits. A binary search finds the last start <= the requested rune.
boundaries = [
    (i << 6) | mask
    for i, mask in enumerate(masks)
    if i == 0 or mask != masks[i - 1]
]
print("// Code generated by generate_unicode.py; DO NOT EDIT.")
print("// Python regex 2026.9.10; mask SHA-256:", digest)
print("package tokenizer")
print()
print("var unicodeBoundaries = [...]uint32{")
for i in range(0, len(boundaries), 8):
    print("\t" + "".join(f"0x{v:07x}, " for v in boundaries[i : i + 8]).rstrip())
print("}")
